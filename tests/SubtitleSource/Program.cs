using System;
using System.Linq;
using AmanatsuLocationVR;
using UnityEngine;
using TMPro;
using ILLGAMES.ADV;
using BepInEx.Logging;

int checks = 0;
void Check(bool condition,string message) { ++checks; if(!condition)throw new Exception(message); }
bool Close(float a,float b) => Math.Abs(a-b)<0.0001f;
var log = new ManualLogSource();
using var source = new SubtitleSource(log);
Check(source.Discover()==null,"Source reported captions before a dialogue window existed.");
int scans=UnityEngine.Object.Scans;
for(int frame=0;frame<20;++frame) Check(source.Discover()==null,"Absent source unexpectedly appeared.");
Check(UnityEngine.Object.Scans==scans,"Missing source discovery scanned every frame.");
Check(log.Infos.Count==1,"Missing source status spammed logs.");
Time.realtimeSinceStartup=1;
var controller = new GameObject("Native dialogue").AddComponent<TextController>();
var parent = new GameObject("Dialogue panel");
var fade = parent.AddComponent<CanvasGroup>(); fade.alpha=.5f;
var message = new GameObject("Message").AddComponent<TextMeshProUGUI>(); message.transform.SetParent(parent.transform,false);
message.font = new TMP_FontAsset(); message.fontSharedMaterial = new Material(); message.text="A native dialogue line.";
message.color=new Color(1,1,1,.8f); message.richText=true; message.fontStyle=FontStyles.Bold; message.maxVisibleCharacters=7;
controller.MessageWindow=message;
controller.NameWindow = new GameObject("Name").AddComponent<TextMeshProUGUI>(); controller.NameWindow.text="Name";
var canvas = source.Discover();
Check(canvas && !canvas.enabled,"Owned caption canvas must start hidden.");
Check(source.Prepare(canvas,42),"Native dialogue could not prepare.");
var clone=UnityEngine.Object.All.OfType<TextMeshProUGUI>().Single(x=>x!=message&&x!=controller.NameWindow&&x.Alive);
Check(clone.text==message.text && clone.font==message.font && clone.fontSharedMaterial==message.fontSharedMaterial,"Native text/font/material did not transfer.");
Check(clone.fontSize==42 && clone.maxVisibleCharacters==7 && clone.fontStyle==FontStyles.Bold && clone.richText,"Font setting/typewriter/style did not transfer.");
Check(Close(clone.color.a,.4f),"Native ancestor fade or message opacity was lost.");
Check(message.enabled && message.text=="A native dialogue line.","Original game text/logic was disabled or modified.");
Check(message.GetComponents<CanvasGroup>().Single().alpha==0,"Original message graphic was not hidden.");
Check(controller.NameWindow.enabled && controller.NameWindow.GetComponents<CanvasGroup>().Length==0,"Name/other dialogue graphic was altered.");
Check(source.HasVisibleText,"Active native dialogue was not visible.");
message.text="Updated translated line"; message.maxVisibleCharacters=12; fade.alpha=.25f;
Check(source.Prepare(canvas,90),"Live dialogue update failed.");
Check(clone.text==message.text && clone.maxVisibleCharacters==12 && clone.fontSize==72 && Close(clone.color.a,.2f),"Live text/typewriter/font bounds/fade update failed.");
Check(message.GetComponents<CanvasGroup>().Length==1,"Suppression groups leaked on repeated frames.");
controller.MessageVisible=false;
Check(!source.HasVisibleText,"Game-hidden dialogue remained visible.");
controller.MessageVisible=true; message.maxVisibleCharacters=0;
Check(!source.HasVisibleText,"Zero-visible-character line remained visible.");
message.maxVisibleCharacters=12;
source.Restore();
Check(message.enabled && message.GetComponents<CanvasGroup>().Length==0 && !canvas.enabled && !source.HasVisibleText,"Disable did not restore original graphic and hide duplicate.");
Check(Close(fade.alpha,.25f),"Native ancestor fade was overwritten.");
Check(source.Prepare(canvas,36),"Capture did not recover after disable.");
message.font = new TMP_FontAsset(); TextMeshProUGUI.ThrowOnNextFont=true;
Check(!source.Prepare(canvas,36),"Font failure was not handled.");
Check(message.GetComponents<CanvasGroup>().Length==0 && !canvas.enabled,"Capture failure left source hidden.");
Check(source.Prepare(canvas,36),"Capture did not recover after font failure.");
var own = message.GetComponents<CanvasGroup>().Single();
var originalLocalGroup=message.gameObject.AddComponent<CanvasGroup>(); originalLocalGroup.alpha=.75f; originalLocalGroup.ignoreParentGroups=true;
Check(source.Prepare(canvas,36)&&Close(clone.color.a,.6f),"ignoreParentGroups opacity semantics were lost.");
message.gameObject.activeInHierarchy=false; Time.realtimeSinceStartup=2;
Check(source.Discover()==null && !own.Alive && originalLocalGroup.Alive,"Scene disappearance failed rollback or removed a game-owned group.");
message.gameObject.activeInHierarchy=true; Time.realtimeSinceStartup=3;
Check(source.Prepare(source.Discover(),36),"Scene recovery failed.");
source.Dispose();
Check(message.GetComponents<CanvasGroup>().Length==1 && originalLocalGroup.Alive && !canvas.Alive,"Dispose did not release only owned caption objects.");
Check(source.Discover()==null && !source.HasVisibleText,"Disposed source remained active.");
Console.WriteLine($"PASS: {checks} native dialogue discovery, clone, visibility, typewriter, fade, rollback and disposal assertions.");
